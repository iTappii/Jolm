CREATE TABLE transport_tariffs (
    version_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode text NOT NULL CHECK (mode IN ('walk', 'scooter', 'bus', 'metro', 'taxi', 'car')),
    valid_from date NOT NULL CHECK (isfinite(valid_from)),
    base_kzt numeric(10, 2) NOT NULL CHECK (base_kzt BETWEEN 0 AND 99999999.99),
    per_min_kzt numeric(10, 2) NOT NULL CHECK (per_min_kzt BETWEEN 0 AND 99999999.99),
    per_km_kzt numeric(10, 2) NOT NULL CHECK (per_km_kzt BETWEEN 0 AND 99999999.99),
    approximate boolean NOT NULL DEFAULT true,
    source text NOT NULL CHECK (length(btrim(source)) BETWEEN 1 AND 200),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (mode <> 'walk' OR base_kzt = 0),
    CHECK (mode <> 'car' OR base_kzt = 0),
    CHECK (mode IN ('scooter', 'taxi') OR per_min_kzt = 0),
    CHECK (mode IN ('taxi', 'car') OR per_km_kzt = 0)
);

CREATE INDEX transport_tariffs_effective_idx
ON transport_tariffs (mode, valid_from DESC, version_id DESC);

CREATE FUNCTION reject_transport_tariff_changes() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'transport_tariffs is append-only' USING ERRCODE = '23000';
END;
$$;

CREATE TRIGGER transport_tariff_history
BEFORE UPDATE OR DELETE OR TRUNCATE ON transport_tariffs
FOR EACH STATEMENT EXECUTE FUNCTION reject_transport_tariff_changes();
