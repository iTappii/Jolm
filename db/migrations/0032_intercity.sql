-- Ш-60: intercity transfers (SSOT §5.4 п. 5). Hubs (airport, station, bus station, city point),
-- links between hubs by mode with approximate duration/price/schedule, and a few named parameters.
-- OPEN(SSOT §16.15): real schedule/price sources are not chosen; the rows come from
-- data/seed/intercity.sql (hand-made estimates with source and as_of), never from the code.

CREATE TABLE intercity_hubs (
    id           text PRIMARY KEY CHECK (id ~ '^[a-z][a-z0-9_-]*$'),
    kind         text NOT NULL CHECK (kind IN ('airport', 'rail', 'bus', 'city')),
    name_ru      text NOT NULL,
    name_en      text NOT NULL,
    city_ru      text NOT NULL,
    city_en      text NOT NULL,
    code         text,                                  -- IATA code for airports
    location     geometry(Point, 4326) NOT NULL,
    -- how far from the hub a point may be and still be served by it (km)
    catchment_km double precision NOT NULL CHECK (catchment_km > 0 AND catchment_km <= 300)
);
CREATE INDEX intercity_hubs_location ON intercity_hubs USING gist (location);

CREATE TABLE intercity_links (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_hub         text NOT NULL REFERENCES intercity_hubs (id),
    to_hub           text NOT NULL REFERENCES intercity_hubs (id),
    mode             text NOT NULL CHECK (mode IN ('plane', 'train', 'bus', 'tour')),
    duration_min_min integer NOT NULL CHECK (duration_min_min > 0),   -- the ride itself, minutes
    duration_max_min integer NOT NULL,
    price_kzt_min    integer CHECK (price_kzt_min >= 0),              -- per person; NULL = unknown
    price_kzt_max    integer,
    transfers        integer NOT NULL DEFAULT 0 CHECK (transfers >= 0),
    -- time to be at the hub before departure (check-in, boarding), minutes
    buffer_min       integer NOT NULL DEFAULT 0 CHECK (buffer_min >= 0),
    -- ISO weekdays 1..7 the service runs; NULL = not known / see departure_hint
    schedule_days    smallint[] CHECK (schedule_days <@ ARRAY[1, 2, 3, 4, 5, 6, 7]::smallint[]),
    departure_hint   text,
    note_ru          text,
    note_en          text,
    source           text NOT NULL CHECK (length(btrim(source)) > 0),
    source_url       text,
    as_of            date NOT NULL,
    approximate      boolean NOT NULL DEFAULT true,
    CHECK (from_hub <> to_hub),
    CHECK (duration_max_min >= duration_min_min),
    CHECK (price_kzt_max IS NULL OR (price_kzt_min IS NOT NULL AND price_kzt_max >= price_kzt_min)),
    UNIQUE (from_hub, to_hub, mode)
);
CREATE INDEX intercity_links_to ON intercity_links (to_hub);

-- Named numbers the intercity code reads (fuel, thresholds...). Not constants of the code.
CREATE TABLE intercity_settings (
    key    text PRIMARY KEY,
    value  numeric NOT NULL,
    unit   text NOT NULL,
    source text NOT NULL,
    as_of  date NOT NULL
);

-- Intercity taxi tariff: a new mode in transport_tariffs (per km, no city traffic factor).
DO $$
DECLARE c record;
BEGIN
    FOR c IN SELECT conname FROM pg_constraint WHERE conrelid = 'transport_tariffs'::regclass AND contype = 'c'
    LOOP
        EXECUTE format('ALTER TABLE transport_tariffs DROP CONSTRAINT %I', c.conname);
    END LOOP;
END $$;

ALTER TABLE transport_tariffs
    ADD CONSTRAINT transport_tariffs_mode_check
        CHECK (mode IN ('walk', 'scooter', 'bus', 'metro', 'taxi', 'car', 'taxi_intercity')),
    ADD CONSTRAINT transport_tariffs_valid_from_check CHECK (isfinite(valid_from)),
    ADD CONSTRAINT transport_tariffs_base_check CHECK (base_kzt BETWEEN 0 AND 99999999.99),
    ADD CONSTRAINT transport_tariffs_per_min_check CHECK (per_min_kzt BETWEEN 0 AND 99999999.99),
    ADD CONSTRAINT transport_tariffs_per_km_check CHECK (per_km_kzt BETWEEN 0 AND 99999999.99),
    ADD CONSTRAINT transport_tariffs_source_check CHECK (length(btrim(source)) BETWEEN 1 AND 200),
    ADD CONSTRAINT transport_tariffs_walk_free CHECK (mode <> 'walk' OR base_kzt = 0),
    ADD CONSTRAINT transport_tariffs_car_no_base CHECK (mode <> 'car' OR base_kzt = 0),
    ADD CONSTRAINT transport_tariffs_per_min_modes CHECK (mode IN ('scooter', 'taxi') OR per_min_kzt = 0),
    ADD CONSTRAINT transport_tariffs_per_km_modes
        CHECK (mode IN ('taxi', 'car', 'taxi_intercity') OR per_km_kzt = 0);
